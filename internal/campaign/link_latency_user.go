type linkLatencyStartupIdentity struct {
	UID, GID, Mode uint32
	Device, Inode  uint64
	Bytes          int64
	SHA256         string
}

func (f linkLatencyStartupIdentity) user() string { return fmt.Sprintf("%d:%d", f.UID, f.GID) }

// The first create uses the owner of this exact private file. No broader mode,
// chown, capability or post-start alternate user is selected after a refusal.
func readLinkLatencyStartup(path string, expected []byte) (identity linkLatencyStartupIdentity, err error) {
	canonical, err := filepath.EvalSymlinks(path)
	if err != nil {
		return identity, err
	}
	if !filepath.IsAbs(path) || canonical != path {
		return identity, errors.New("startup configuration path is not canonical")
	}
	before, err := os.Lstat(path)
	if err != nil {
		return identity, err
	}
	st, ok := before.Sys().(*syscall.Stat_t)
	if !ok || !before.Mode().IsRegular() || before.Mode().Perm() != 0600 || before.Size() <= 0 || before.Size() > 16<<10 || st.Nlink != 1 || st.Uid == 0 || st.Uid != uint32(os.Geteuid()) {
		return identity, errors.New("startup configuration requires current nonroot owner, single link and exact0600 mode")
	}
	f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return identity, err
	}
	opened, openErr := f.Stat()
	if openErr != nil || !os.SameFile(before, opened) {
		return identity, errors.Join(openErr, errors.New("startup configuration changed before read"), f.Close())
	}
	body, readErr := io.ReadAll(io.LimitReader(f, (16<<10)+1))
	after, statErr := f.Stat()
	closeErr := f.Close()
	current, pathErr := os.Lstat(path)
	if err = errors.Join(readErr, statErr, closeErr, pathErr); err != nil {
		return identity, err
	}
	if len(body) > 16<<10 || !os.SameFile(before, after) || !os.SameFile(before, current) || before.Size() != after.Size() || before.ModTime() != after.ModTime() || expected != nil && !bytes.Equal(body, expected) {
		return identity, errors.New("startup configuration identity or generated bytes changed")
	}
	for _, observed := range []os.FileInfo{opened, after, current} {
		actual, ok := observed.Sys().(*syscall.Stat_t)
		if !ok || observed.Mode().Perm() != 0600 || actual.Uid != st.Uid || actual.Gid != st.Gid || actual.Nlink != 1 {
			return identity, errors.New("startup configuration ownership or mode changed during read")
		}
	}
	return linkLatencyStartupIdentity{st.Uid, st.Gid, uint32(before.Mode().Perm()), uint64(st.Dev), st.Ino, before.Size(), processDigest(body)}, nil
}

func validateLinkLatencyStartup(plan linkCalibrationLatencyPlan) error {
	actual, err := readLinkLatencyStartup(plan.ConfigPath, nil)
	if err != nil {
		return err
	}
	if plan.ConfigFile != actual || plan.User != actual.user() {
		return errors.New("planned startup file owner, bytes or numeric user changed")
	}
	return nil
}

func linkLatencyCreateArguments(s fixture.State, p linkCalibrationLatencyPlan, platform string) ([]string, error) {
	actualPlatform, image, imageID, err := selectedLinkCalibrationProxy(s)
	if err != nil {
		return nil, err
	}
	prefix := s.Proxy.Container + "-latency-"
	suffix := strings.TrimPrefix(p.Name, prefix)
	expectedPath, pathErr := filepath.Abs(filepath.Join(".cache", "fixtures", s.RunID+"-links", p.Name, "startup.json"))
	host, port, apiErr := net.SplitHostPort(p.API)
	if pathErr != nil || apiErr != nil || host != "127.0.0.1" || port == "" || p.ConfigPath != expectedPath || actualPlatform != platform || !strings.HasPrefix(p.Name, prefix) || len(suffix) != 16 || !calibrationHex(suffix) || p.RunID != s.RunID || p.Role != "latency-calibration" || p.Image != image || p.ExpectedImageID != imageID || p.Network != "host" || len(p.Command) != 3 || p.MemoryBytes != 128<<20 || p.NanoCPUs != 500000000 || p.PIDs != 64 || p.LogBytes != 1<<20 {
		return nil, errors.New("latency first-create plan differs from fixed owned contract")
	}
	if p.Command[0] != "-host=127.0.0.1" || p.Command[1] != "-port="+port || p.Command[2] != "-config=/calibration.json" {
		return nil, errors.New("latency first-create command differs from fixed startup selection")
	}
	if err := validateLinkLatencyStartup(p); err != nil {
		return nil, err
	}
	args := []string{"container", "create", "--name", p.Name, "--network", "host", "--platform", platform, "--user", p.User, "--pull=never", "--memory", "128m", "--cpus", "0.5", "--pids-limit", "64", "--read-only", "--cap-drop", "ALL", "--security-opt", "no-new-privileges", "--log-driver", "json-file", "--log-opt", "max-size=1m", "--log-opt", "max-file=1", "--label", brokerOwnerLabel + "=" + s.RunID, "--label", "io.kaferry-lab.role=latency-calibration", "--mount", "type=bind,src=" + p.ConfigPath + ",dst=/calibration.json,readonly", image}
	return append(args, p.Command...), nil
}
